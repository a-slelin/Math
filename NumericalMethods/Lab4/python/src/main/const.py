# Здесь собраны все исходные данные задачи (вариант 10).
# Решаем задачу Дирихле для уравнения Лапласа:
#
#     d²u/dx² + d²u/dy² = 0   внутри области D,
#     u = phi(x, y)           на границе Г.
#
# Область D — эллипс  x²/16 + y²/25 < 1,  значения на границе  u|Г = |x| * |y|.

# Полуоси эллипса: по x это 4, по y это 5
semi_x = 4.0
semi_y = 5.0


# "Уравнение эллипса": F(x, y) = x²/16 + y²/25.
# Если F < 1 — точка внутри, F = 1 — на границе, F > 1 — снаружи.
def ellipse(x, y):
    return x ** 2 / semi_x ** 2 + y ** 2 / semi_y ** 2


# Значения на границе: phi(x, y) = |x| * |y|
def phi(x, y):
    return abs(x) * abs(y)


