# Здесь собраны все исходные данные задачи (вариант 13).
# Решаем краевую задачу для обыкновенного дифференциального уравнения:
#
#     y'' + p * y' + q * y = f(x),    a <= x <= b,
#
#     alpha1 * y(a) + beta1 * y'(a) = gamma1,
#     alpha2 * y(b) + beta2 * y'(b) = gamma2.
#
# У нас:  y'' + 2y' - 3y = e^x,   y(0) = 0,   y'(1) = 1,   n = 20.

# Отрезок [a, b]
a = 0.0
b = 1.0

# Коэффициенты уравнения y'' + p*y' + q*y = f(x)
p = 2.0
q = -3.0


# Правая часть уравнения f(x) = e^x
def f(x):
    return np.exp(x)


# Левое краевое условие: alpha1 * y(0) + beta1 * y'(0) = gamma1,
# у нас это просто y(0) = 0
alpha1, beta1, gamma1 = 1.0, 0.0, 0.0

# Правое краевое условие: alpha2 * y(1) + beta2 * y'(1) = gamma2,
# у нас это просто y'(1) = 1
alpha2, beta2, gamma2 = 0.0, 1.0, 1.0

# На сколько отрезков делим [a, b] (по заданию n = 20)
n = 20

# Константа C1 из точного решения (вывод есть в README.md):
# C1 = (1 - e/2) / (e + 3 * e^(-3))
C1 = (1 - np.e / 2) / (np.e + 3 * np.exp(-3))


# Точное (аналитическое) решение, найденное руками:
# y(x) = C1 * (e^x - e^(-3x)) + x * e^x / 4
def exact(x):
    return C1 * (np.exp(x) - np.exp(-3 * x)) + x * np.exp(x) / 4


