# Здесь собраны все исходные данные задачи (вариант 13).
# Решаем краевую задачу для уравнения теплопроводности:
#
#     du/dt = d²u/dx² + f(x, t),   0 <= x <= 1,   t >= 0,
#
#     u(x, 0) = phi(x)                                  — начальное условие,
#     alpha1 * u(0, t) + beta1 * du/dx(0, t) = gamma1(t) — левое краевое условие,
#     alpha2 * u(1, t) + beta2 * du/dx(1, t) = gamma2(t) — правое краевое условие.
#
# У нас:  du/dt = d²u/dx² + (1 - t)*e^(-x),   u(x, 0) = 0,   u(0, t) = t,   u(1, t) = t/e.


# Правая часть уравнения f(x, t) = (1 - t) * e^(-x)
def f(x, t):
    return (1 - t) * np.exp(-x)


# Вторая производная правой части по x (нужна для схемы повышенного порядка).
# (e^(-x))'' = e^(-x), поэтому f''_xx совпадает с самой f.
def f_xx(x, t):
    return (1 - t) * np.exp(-x)


# Начальное условие u(x, 0) = 0
def phi(x):
    return np.zeros_like(x)


# Левое краевое условие: 1 * u(0, t) + 0 * u'(0, t) = t
alpha1, beta1 = 1.0, 0.0


def gamma1(t):
    return t


# Правое краевое условие: 1 * u(1, t) + 0 * u'(1, t) = t / e
alpha2, beta2 = 1.0, 0.0


def gamma2(t):
    return t * np.exp(-1)


# Точное решение (вывод есть в README.md): u(x, t) = t * e^(-x)
def exact(x, t):
    return t * np.exp(-x)


