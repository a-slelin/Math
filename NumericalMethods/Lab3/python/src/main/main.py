import matplotlib.pyplot as plt


# Главная функция лабораторной работы №3.
# Здесь будет решение задачи; пока что это заготовка,
# которая просто открывает пустое окно с графиком.
def main():
    # Создаём окно с одной областью для рисования
    fig, ax = plt.subplots()

    # Включаем сетку, чтобы график было легче читать
    ax.grid(True)

    # Подписываем график
    ax.set_title('Лабораторная работа №3')
    ax.set_xlabel('x')
    ax.set_ylabel('y')

    # Показываем окно
    plt.show()


if __name__ == '__main__':
    main()
