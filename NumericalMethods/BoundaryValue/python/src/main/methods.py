import numpy as np
from const import a, b, p, q, f, alpha1, beta1, gamma1, alpha2, beta2, gamma2


# ---------------------------------------------------------------------------
# Шаг 1. Строим разностную (сеточную) задачу.
#
# Производные заменяем разностями (как в методичке):
#     y'(x_i)  ≈ (y_(i+1) - y_i) / h,
#     y''(x_i) ≈ (y_(i-1) - 2*y_i + y_(i+1)) / h².
#
# Подставляем в уравнение, умножаем на h² и собираем слагаемые при
# y_(i-1), y_i, y_(i+1). Получаем уравнения вида (6.5):
#     y_(i-1) + d_i * y_i + e_i * y_(i+1) = g_i,   i = 1, ..., n-1,
# где
#     d_i = -2 - p*h + q*h²,   e_i = 1 + p*h,   g_i = h² * f(x_i).
#
# Краевые условия записываем в виде (6.6):
#     y_0 = chi1 * y_1 + mu1,
#     y_n = chi2 * y_(n-1) + mu2.
# ---------------------------------------------------------------------------
def build_grid_problem(n):
    # Шаг сетки и сами узлы x_0, x_1, ..., x_n
    h = (b - a) / n
    x = np.linspace(a, b, n + 1)

    # Коэффициенты d_i, e_i, g_i. Храним массивы длины n + 1,
    # чтобы номер в массиве совпадал с номером узла i
    # (элементы с номерами 0 и n просто не используются).
    d = np.full(n + 1, -2 - p * h + q * h ** 2)
    e = np.full(n + 1, 1 + p * h)
    g = h ** 2 * f(x)

    # Левое условие: alpha1*y_0 + beta1*(y_1 - y_0)/h = gamma1.
    # Умножаем на h и выражаем y_0 через y_1:
    #     y_0 = -beta1 / (alpha1*h - beta1) * y_1 + gamma1*h / (alpha1*h - beta1)
    chi1 = -beta1 / (alpha1 * h - beta1)
    mu1 = gamma1 * h / (alpha1 * h - beta1)

    # Правое условие: alpha2*y_n + beta2*(y_n - y_(n-1))/h = gamma2.
    # Умножаем на h и выражаем y_n через y_(n-1):
    #     y_n = beta2 / (alpha2*h + beta2) * y_(n-1) + gamma2*h / (alpha2*h + beta2)
    chi2 = beta2 / (alpha2 * h + beta2)
    mu2 = gamma2 * h / (alpha2 * h + beta2)

    return x, d, e, g, chi1, mu1, chi2, mu2


# ---------------------------------------------------------------------------
# Метод 1. Правая (прямая) прогонка.
#
# Идея: каждое y_i выражаем через следующее y_(i+1):
#     y_i = Q_i * y_(i+1) + F_i.
# Сначала идём слева направо и считаем все Q_i, F_i ("прямой ход"),
# потом находим y_n и идём справа налево, восстанавливая y_i ("обратный ход").
# (В методичке Q и F обозначены как q и φ; мы пишем большие буквы,
# чтобы не путать с коэффициентом q из уравнения.)
# ---------------------------------------------------------------------------
def right_sweep(d, e, g, chi1, mu1, chi2, mu2):
    n = len(d) - 1
    Q = np.zeros(n + 1)
    F = np.zeros(n + 1)

    # Из левого условия y_0 = chi1*y_1 + mu1 сразу видно: Q_0 = chi1, F_0 = mu1
    Q[0] = chi1
    F[0] = mu1

    # Прямой ход: подставляем y_(i-1) = Q_(i-1)*y_i + F_(i-1) в i-е уравнение
    # и выражаем y_i через y_(i+1)
    for i in range(1, n):
        denominator = Q[i - 1] + d[i]
        Q[i] = -e[i] / denominator
        F[i] = (g[i] - F[i - 1]) / denominator

    # Находим y_n из системы: y_(n-1) = Q_(n-1)*y_n + F_(n-1) и y_n = chi2*y_(n-1) + mu2
    y = np.zeros(n + 1)
    y[n] = (mu2 + chi2 * F[n - 1]) / (1 - Q[n - 1] * chi2)

    # Обратный ход: идём справа налево
    for i in range(n - 1, -1, -1):
        y[i] = Q[i] * y[i + 1] + F[i]

    return y


# ---------------------------------------------------------------------------
# Метод 2. Левая (обратная) прогонка.
#
# То же самое, но в другую сторону: выражаем y_(i+1) через y_i:
#     y_(i+1) = xi_(i+1) * y_i + eta_(i+1).
# Сначала идём справа налево и считаем xi_i, eta_i,
# потом находим y_0 и идём слева направо.
# ---------------------------------------------------------------------------
def left_sweep(d, e, g, chi1, mu1, chi2, mu2):
    n = len(d) - 1
    xi = np.zeros(n + 1)
    eta = np.zeros(n + 1)

    # Из правого условия y_n = chi2*y_(n-1) + mu2 сразу видно: xi_n = chi2, eta_n = mu2
    xi[n] = chi2
    eta[n] = mu2

    # Подставляем y_(i+1) = xi_(i+1)*y_i + eta_(i+1) в i-е уравнение
    # и выражаем y_i через y_(i-1)
    for i in range(n - 1, 0, -1):
        denominator = d[i] + e[i] * xi[i + 1]
        xi[i] = -1 / denominator
        eta[i] = (g[i] - e[i] * eta[i + 1]) / denominator

    # Находим y_0 из системы: y_1 = xi_1*y_0 + eta_1 и y_0 = chi1*y_1 + mu1
    y = np.zeros(n + 1)
    y[0] = (mu1 + chi1 * eta[1]) / (1 - chi1 * xi[1])

    # Идём слева направо
    for i in range(0, n):
        y[i + 1] = xi[i + 1] * y[i] + eta[i + 1]

    return y


# ---------------------------------------------------------------------------
# Метод 3. Встречная прогонка.
#
# Запускаем правую прогонку слева до узла k, а левую прогонку справа
# до узла k+1. "Встречаемся" посередине, находим y_k и y_(k+1),
# а потом расходимся в обе стороны.
# ---------------------------------------------------------------------------
def meeting_sweep(d, e, g, chi1, mu1, chi2, mu2, k=None):
    n = len(d) - 1

    # Точка встречи: по умолчанию середина отрезка
    if k is None:
        k = n // 2

    # Правая прогонка слева направо до узла k
    Q = np.zeros(n + 1)
    F = np.zeros(n + 1)
    Q[0] = chi1
    F[0] = mu1
    for i in range(1, k + 1):
        denominator = Q[i - 1] + d[i]
        Q[i] = -e[i] / denominator
        F[i] = (g[i] - F[i - 1]) / denominator

    # Левая прогонка справа налево до узла k+1
    xi = np.zeros(n + 1)
    eta = np.zeros(n + 1)
    xi[n] = chi2
    eta[n] = mu2
    for i in range(n - 1, k, -1):
        denominator = d[i] + e[i] * xi[i + 1]
        xi[i] = -1 / denominator
        eta[i] = (g[i] - e[i] * eta[i + 1]) / denominator

    # Система из двух уравнений:
    #     y_k     = Q_k * y_(k+1) + F_k,
    #     y_(k+1) = xi_(k+1) * y_k + eta_(k+1).
    # Подставляем второе в первое и находим y_k, а затем y_(k+1)
    y = np.zeros(n + 1)
    y[k] = (Q[k] * eta[k + 1] + F[k]) / (1 - Q[k] * xi[k + 1])
    y[k + 1] = xi[k + 1] * y[k] + eta[k + 1]

    # Идём от точки встречи влево (формулы правой прогонки)
    for i in range(k - 1, -1, -1):
        y[i] = Q[i] * y[i + 1] + F[i]

    # Идём от точки встречи вправо (формулы левой прогонки)
    for i in range(k + 1, n):
        y[i + 1] = xi[i + 1] * y[i] + eta[i + 1]

    return y


# ---------------------------------------------------------------------------
# Метод 4. Метод стрельбы (пристрелки).
#
# Если знать y_0 и y_1, то из уравнения
#     y_(i-1) + d_i*y_i + e_i*y_(i+1) = g_i
# можно по очереди найти y_2, y_3, ..., y_n:
#     y_(i+1) = (g_i - y_(i-1) - d_i*y_i) / e_i.
#
# Решение ищем в виде Y = C1*U + C2*V + W, где
#     U — решение без правой части с началом u_0 = 0, u_1 = 1,
#     V — решение без правой части с началом v_0 = 1, v_1 = 0,
#     W — решение с правой частью g с началом w_0 = 0, w_1 = 0.
# Числа C1 и C2 подбираем так, чтобы выполнились оба краевых условия.
# ---------------------------------------------------------------------------
def shooting(d, e, g, chi1, mu1, chi2, mu2):
    n = len(d) - 1

    # "Выстрел": по двум стартовым значениям и правой части строим всю последовательность
    def shoot(start0, start1, rhs):
        y = np.zeros(n + 1)
        y[0] = start0
        y[1] = start1
        for i in range(1, n):
            y[i + 1] = (rhs[i] - y[i - 1] - d[i] * y[i]) / e[i]
        return y

    zero = np.zeros(n + 1)
    U = shoot(0.0, 1.0, zero)
    V = shoot(1.0, 0.0, zero)
    W = shoot(0.0, 0.0, g)

    # У Y = C1*U + C2*V + W получается y_0 = C2 и y_1 = C1.
    # Левое условие y_0 = chi1*y_1 + mu1 даёт:   C2 = chi1*C1 + mu1.
    # Правое условие y_n = chi2*y_(n-1) + mu2 даёт:
    #     C1*A + C2*B = R,
    # где A = u_n - chi2*u_(n-1), B = v_n - chi2*v_(n-1), R = mu2 - w_n + chi2*w_(n-1).
    A = U[n] - chi2 * U[n - 1]
    B = V[n] - chi2 * V[n - 1]
    R = mu2 - W[n] + chi2 * W[n - 1]

    # Подставляем C2 из левого условия в правое и находим C1, потом C2
    C1 = (R - mu1 * B) / (A + chi1 * B)
    C2 = chi1 * C1 + mu1

    return C1 * U + C2 * V + W


# Все четыре метода в одном словаре: "название" -> функция
METHODS = {
    'Правая прогонка': right_sweep,
    'Левая прогонка': left_sweep,
    'Встречная прогонка': meeting_sweep,
    'Метод стрельбы': shooting,
}
